export const FOOD_MONTHS = FOOD_GROUPS.map((g) => g.month);

/** 食材名稱 → 建議順序編號。名稱不重複，所以可以當識別。 */
export const FOOD_NUMBERS: ReadonlyMap<string, number> = new Map(
  FOOD_GROUPS.flatMap((g) => g.items.map(([no, name]) => [name, no] as const)),
);

export function isCatalogFood(name: string): boolean {
  return FOOD_NUMBERS.has(name);
}

/** 依月齡決定標示哪一區：未滿 4 個月不標，10 個月以上標 10 個月。 */
export function currentMonthGroup(ageMonths: number): number | null {
  if (!Number.isFinite(ageMonths) || ageMonths < 4) return null;
  return Math.min(Math.floor(ageMonths), 10);
}
